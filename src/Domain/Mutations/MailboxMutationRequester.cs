using System.Buffers;
using System.Globalization;

namespace MailFathom.Domain.Mutations;

/// <summary>Names the authored act that asked for a mutation, in a form two requests can be compared by.</summary>
/// <remarks>
/// <para>
/// This is one third of a mutation's idempotency identity, beside the email occurrence and the mutation itself. It has
/// to answer one question: would asking again be the same request or a new one. A rule answers it with its own name and
/// the revision it was evaluated at, so re-evaluating an unchanged rule over the same email performs nothing and
/// changing the rule asks afresh. An invocation answers it with the identity of the invocation, so a retried call is
/// the same request and a second call is a second one.
/// </para>
/// <para>
/// Only MailFathom's own configured names reach here. A rule name and an invocation identity are chosen by the operator
/// or generated by MailFathom; no subject, address, or other mail content is part of a requester, which is what keeps
/// the mutation record free of message content while still saying who asked.
/// </para>
/// </remarks>
public sealed record MailboxMutationRequester
{
    /// <summary>The greatest length an identity may have, which bounds the column it is stored in and the index over it.</summary>
    public const int MaximumIdentityLength = 128;

    /// <summary>The character a composed identity is written with, and which therefore cannot appear inside its parts.</summary>
    /// <remarks>
    /// One character rather than the two an outgoing email's identity is composed with, because a mutation's identity is
    /// composed of two parts rather than three. It is held as a set so that composing a third part later refuses the
    /// character that separates it in the same place as this one.
    /// </remarks>
    private static readonly SearchValues<char> ComposedIdentitySeparators = SearchValues.Create(['@']);

    private MailboxMutationRequester(MailboxMutationOrigin origin, string identity)
    {
        this.Origin = origin;
        this.Identity = identity;
    }

    /// <summary>Gets what kind of authored act asked.</summary>
    public MailboxMutationOrigin Origin { get; }

    /// <summary>Gets the identity that decides whether asking again is the same request.</summary>
    public string Identity { get; }

    /// <summary>Names a rule together with the revision of it that asked.</summary>
    /// <param name="ruleName">The operator's own name for the rule.</param>
    /// <param name="revision">The identity of the rule set revision the request was produced from.</param>
    /// <returns>A requester naming that revision of that rule.</returns>
    /// <exception cref="ArgumentException">Thrown when <paramref name="ruleName" /> or <paramref name="revision" /> is blank, carries a control character, carries the <c>@</c> character the identity is composed with, or is long enough that the composed identity exceeds <see cref="MaximumIdentityLength" />.</exception>
    /// <remarks>
    /// The revision is part of the identity rather than a column beside it, because the comparison that matters is
    /// equality of the whole thing: an edited rule is a different requester and asks again, while an unchanged one
    /// re-evaluated on every pass asks once. It is text rather than a counter because the revision a rule set is known
    /// by is a digest over its own declarations, which is what makes two instances reading one file agree on it.
    /// </remarks>
    public static MailboxMutationRequester Rule(string ruleName, string revision)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(ruleName);
        ArgumentException.ThrowIfNullOrWhiteSpace(revision);

        var trimmedRuleName = ValidComposedPart(ruleName, nameof(ruleName));
        var trimmedRevision = ValidComposedPart(revision, nameof(revision));

        var identity = string.Create(CultureInfo.InvariantCulture, $"{trimmedRuleName}@{trimmedRevision}");

        // Reported against the rule name rather than against the composed identity, because that is the part the caller
        // supplied and the only part they can shorten.
        return new MailboxMutationRequester(MailboxMutationOrigin.Rule, ValidIdentity(identity, nameof(ruleName)));
    }

    /// <summary>Names the profile a spam classification was decided under, which is what asked for the mutation.</summary>
    /// <param name="decidedUnder">What the deciding stage ran under — a scanner's rule corpus, or the stage's own name where it has none.</param>
    /// <param name="actingThreshold">The score MailFathom itself requires before it touches mail, or <see langword="null" /> when the operator configured none.</param>
    /// <returns>A requester naming that profile.</returns>
    /// <exception cref="ArgumentException">Thrown when <paramref name="decidedUnder" /> is blank, carries a control character, carries the <c>@</c> character the identity is composed with, or is long enough that the composed identity exceeds <see cref="MaximumIdentityLength" />.</exception>
    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="actingThreshold" /> is not a finite number.</exception>
    /// <remarks>
    /// <para>
    /// A classification asks the way a rule does — on its own, repeatedly, about mail nobody is looking at — so it needs
    /// the same kind of identity: one that does not move when the same decision is reached again, and does move when the
    /// terms of the decision change. What a rule answers with its name and revision, a classification answers with the
    /// corpus its verdict was reached against and the threshold MailFathom would act at. Rescanning the same message
    /// against the same corpus therefore asks for nothing new, and a corpus update or a threshold an operator moved asks
    /// afresh.
    /// </para>
    /// <para>
    /// The occurrence is deliberately not part of this text. It is already the first third of the record's own
    /// idempotency identity, so repeating it here would spend the identity's length on a value the constraint already
    /// compares.
    /// </para>
    /// </remarks>
    public static MailboxMutationRequester Classification(string decidedUnder, double? actingThreshold)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(decidedUnder);

        if (actingThreshold is { } threshold && !double.IsFinite(threshold))
        {
            throw new ArgumentOutOfRangeException(
                nameof(actingThreshold),
                threshold,
                "An acting threshold is a finite number.");
        }

        var identity = string.Create(
            CultureInfo.InvariantCulture,
            $"{ValidComposedPart(decidedUnder, nameof(decidedUnder))}@{DescribeThreshold(actingThreshold)}");

        // Reported against the corpus rather than against the composed identity, for the reason the rule factory gives:
        // it is the part the caller supplied and the only part they can shorten.
        return new MailboxMutationRequester(
            MailboxMutationOrigin.Classification,
            ValidIdentity(identity, nameof(decidedUnder)));
    }

    /// <summary>Names one invocation somebody made.</summary>
    /// <param name="invocationIdentity">The identity of the invocation, which is the same for a retry of it and different for a second one.</param>
    /// <returns>A requester naming that invocation.</returns>
    /// <exception cref="ArgumentException">Thrown when <paramref name="invocationIdentity" /> is blank, carries a control character, or is longer than <see cref="MaximumIdentityLength" />.</exception>
    public static MailboxMutationRequester Command(string invocationIdentity) => new(
        MailboxMutationOrigin.Command,
        ValidIdentity(invocationIdentity, nameof(invocationIdentity)));

    /// <summary>Restores a requester from the origin and identity a record holds.</summary>
    /// <param name="origin">The kind of authored act that asked.</param>
    /// <param name="identity">The stored identity.</param>
    /// <returns>The requester those two name.</returns>
    /// <exception cref="ArgumentException">Thrown when <paramref name="identity" /> is blank, carries a control character, or is longer than <see cref="MaximumIdentityLength" />.</exception>
    /// <exception cref="ArgumentOutOfRangeException">Thrown when <paramref name="origin" /> is not a declared origin.</exception>
    public static MailboxMutationRequester Create(MailboxMutationOrigin origin, string identity)
    {
        if (!Enum.IsDefined(origin))
        {
            throw new ArgumentOutOfRangeException(
                nameof(origin),
                origin,
                "The mutation requester origin is not one this system declares.");
        }

        return new MailboxMutationRequester(origin, ValidIdentity(identity, nameof(identity)));
    }

    /// <summary>Writes the acting threshold into the identity, with a name of its own for the absent case.</summary>
    /// <remarks>
    /// An unconfigured threshold is written rather than left out, so that configuring one changes the identity instead of
    /// producing text that could also be read as a corpus nobody judged. The invariant culture is what keeps two
    /// instances of one deployment agreeing on the identity whatever locale each process starts under.
    /// </remarks>
    private static string DescribeThreshold(double? actingThreshold) => actingThreshold is { } threshold
        ? threshold.ToString(CultureInfo.InvariantCulture)
        : "none";

    /// <summary>Validates one part of a composed identity, including that it cannot be mistaken for another split of it.</summary>
    /// <remarks>
    /// The separator is refused rather than escaped, because what a composed identity has to guarantee is that two
    /// distinct pairs cannot write the same string: a rule named <c>a</c> at revision <c>b@c</c> and a rule named
    /// <c>a@b</c> at revision <c>c</c> would otherwise compose one identity, and the unique index would read the second
    /// rule's genuine request as a repeat of the first one's and perform nothing. Neither a rule name an operator wrote
    /// nor a scanner corpus name carries an at-sign, so refusing it costs nothing a caller can legitimately want.
    /// </remarks>
    private static string ValidComposedPart(string identityPart, string parameterName)
    {
        var trimmedPart = identityPart.Trim();

        if (trimmedPart.AsSpan().ContainsAny(ComposedIdentitySeparators))
        {
            throw new ArgumentException(
                "A part of a composed mutation requester identity cannot contain the character it is composed with.",
                parameterName);
        }

        return trimmedPart;
    }

    /// <summary>Validates an identity and reports a refusal against the parameter the caller actually supplied.</summary>
    /// <remarks>
    /// The parameter name travels in rather than being taken from this method's own signature, because every factory
    /// above names its input differently and a refusal naming a parameter the caller never wrote is a refusal they
    /// cannot act on.
    /// </remarks>
    private static string ValidIdentity(string identity, string parameterName)
    {
        ArgumentException.ThrowIfNullOrWhiteSpace(identity, parameterName);

        var trimmedIdentity = identity.Trim();

        if (trimmedIdentity.Length > MaximumIdentityLength)
        {
            throw new ArgumentException(
                $"A mutation requester identity may be at most {MaximumIdentityLength} characters long.",
                parameterName);
        }

        // A control character would make the identity unreadable in the audit query the record exists to serve, and it
        // is never part of a name an operator wrote or an identity MailFathom generated.
        if (trimmedIdentity.Any(char.IsControl))
        {
            throw new ArgumentException(
                "A mutation requester identity cannot contain a control character.",
                parameterName);
        }

        return trimmedIdentity;
    }

    /// <inheritdoc />
    public override string ToString() => $"{this.Origin}:{this.Identity}";
}
